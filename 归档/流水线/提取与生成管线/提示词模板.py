# -*- coding: utf-8 -*-
"""Q/A 实验共享提示词模板（唯一副本）。

设计约束：Q/A 两组提示词，除「任务行」外必须逐字相同——这是实验的
唯一自变量（Q=给定研究问题、自下而上分析；A=给定顶层观点、以论带史）。
本模块承载硬性要求/史料池/结尾指令的唯一副本，两个生成脚本都从这里渲染，
从结构上杜绝「两份模板手动维护」造成的变量漂移。

任务行由调用方拼接：
  Q 组：你是一位{role}，请基于以下史料池，分析{question}。
  A 组：你是一位{role}，请基于以下史料池，论证以下核心观点：
        【观点】{A_H}
"""
TIER_LABEL = {"S": "核心文本", "M": "核心文本前后各100字符", "L": "核心文本前后各200字符", "AUTO": "全量"}

BODY = """【硬性要求——必须全部满足】
1. 严格依据所给史料展开论证，不得引入额外史料或现代学术观点；若史料不足以下结论，请显式说明"史料不足，难以判断"。
2. 论文必须使用小标题分层组织（用于后续结构化抽取），标题层级形如：
   - 一级标题：一、xxxx
   - 二级标题（如有）：(一) xxxx
   - 三级标题（如有）：1. xxxx
   分级数量、层级深度**由内容本身需要决定**，不得为凑数量而增设或删并标题；每个标题下至少有一个正文段落。
   - 一级标题的数量与措辞由史料和论点自行决定，贴合史料实际内容
3. 必须引用至少 15 条不同的 SRC 史料编号（形如 [SRC_001_P01]、[SRC_002_P01] 等），且每条引用与论点直接相关；不得集中堆在同一段。
4. 正文字数不少于 4000 字（中文），不含标题与编号标记；目标 5000 字。
5. 输出格式：纯文本（不要 markdown 代码块标记 ```），章节标题独占一行。
6. 不要在论文之外输出任何说明、注释、meta 信息或重述提示词。"""

TAIL = "请直接从论文标题（独占一行，不含\"标题:\"前缀）开始撰写。"


def render_prompt(task_line, S_block, tier):
    """任务行 + 统一正文 + 史料池 + 统一结尾。"""
    tier_label = TIER_LABEL.get(tier, tier)
    return f"""{task_line}

{BODY}

【史料池（{tier_label}）】
{S_block}

{TAIL}
"""